def _require_local_database() -> None:
    url = os.environ.get("DATABASE_URL", "")
    if not any(host in url for host in ("localhost", "127.0.0.1", "host.docker.internal")):
        sys.exit("Refusing to seed sample data: DATABASE_URL is not a local database.")


async def seed() -> None:
    await create_pool()
    _require_local_database()
    try:
        async with get_pool().acquire() as conn:
            owner_id = await conn.fetchval(
                "SELECT id FROM users WHERE is_super_admin AND is_active ORDER BY created_at LIMIT 1"
            )
            columns = list(zip(*SAMPLES))
            inserted = await conn.fetch(
                """
                INSERT INTO initiatives (name, brand_id, channel_id, sub_channel_id, owner_user_id,
                                         start_date, end_date, budget_amount, currency, status,
                                         created_by, updated_by)
                SELECT s.name, b.id, c.id, sc.id, $10, s.start_date, s.end_date, s.budget, s.currency, s.status,
                       $10, $10
                FROM unnest($1::text[], $2::text[], $3::text[], $4::text[], $5::date[], $6::date[],
                            $7::numeric[], $8::text[], $9::text[])
                     AS s(name, brand, channel, sub_channel, start_date, end_date, budget, currency, status)
                JOIN brands b ON b.code = s.brand
                JOIN channels c ON c.code = s.channel
                JOIN sub_channels sc ON sc.code = s.sub_channel
                WHERE NOT EXISTS (SELECT 1 FROM initiatives i WHERE i.name = s.name)
                RETURNING name
                """,
                *[list(col) for col in columns],
                owner_id,
            )

            # Only events without details yet, so re-running never uses up event code numbers
            detail_columns = list(zip(*EVENT_DETAILS))
            details = await conn.fetch(
                """
                INSERT INTO event_details (initiative_id, event_type_id, venue, city, country_code, region_id,
                                           created_by, updated_by)
                SELECT i.id, et.id, d.venue, d.city, d.country_code, r.id, $7, $7
                FROM unnest($1::text[], $2::text[], $3::text[], $4::text[], $5::text[], $6::text[])
                     AS d(name, event_type, venue, city, country_code, region)
                JOIN initiatives i ON i.name = d.name
                LEFT JOIN event_types et ON et.code = d.event_type
                LEFT JOIN regions r ON r.code = d.region
                WHERE NOT EXISTS (SELECT 1 FROM event_details e WHERE e.initiative_id = i.id)
                RETURNING event_code
                """,
                *[list(col) for col in detail_columns],
                owner_id,
            )

            # Only initiatives without costs yet, so re-running never duplicates them
            cost_columns = list(zip(*SPEND_LINES))
            costs = await conn.fetch(
                """
                INSERT INTO spend_lines (initiative_id, category_id, description, vendor, status, estimated_amount,
                                         amount, currency, incurred_on, invoice_ref, paid_on, payment_method,
                                         source, cost_type, created_by, updated_by)
                SELECT i.id, sc.id, l.description, l.vendor, l.status, l.estimated_amount, l.amount, l.currency,
                       l.incurred_on, l.invoice_ref, l.paid_on, l.payment_method, l.source, sc.default_cost_type,
                       $14, $14
                FROM unnest($1::text[], $2::text[], $3::text[], $4::text[], $5::text[], $6::numeric[],
                            $7::numeric[], $8::text[], $9::date[], $10::text[], $11::date[], $12::text[], $13::text[])
                     AS l(name, category, description, vendor, status, estimated_amount, amount, currency,
                          incurred_on, invoice_ref, paid_on, payment_method, source)
                JOIN initiatives i ON i.name = l.name
                JOIN spend_categories sc ON sc.code = l.category
                WHERE NOT EXISTS (SELECT 1 FROM spend_lines s WHERE s.initiative_id = i.id)
                RETURNING amount
                """,
                *[list(col) for col in cost_columns],
                owner_id,
            )

            # Only events without demos yet, so re-running never duplicates them
            demo_columns = list(zip(*DEMOS))
            demos = await conn.fetch(
                """
                INSERT INTO event_demos (initiative_id, demo_at, demo_type_id, company, brand_id, product_note,
                                         given_by, outcome_id, outcome_updated_at, source, created_by, updated_by)
                SELECT i.id, d.demo_at, dt.id, d.company, i.brand_id, d.product, $7, o.id,
                       CASE WHEN o.code <> 'PENDING' THEN d.demo_at + interval '14 days' END, 'MANUAL', $7, $7
                FROM unnest($1::text[], $2::timestamptz[], $3::text[], $4::text[], $5::text[], $6::text[])
                     AS d(name, demo_at, demo_type, company, product, outcome)
                JOIN initiatives i ON i.name = d.name
                JOIN demo_types dt ON dt.code = d.demo_type
                JOIN demo_outcomes o ON o.code = d.outcome
                WHERE NOT EXISTS (SELECT 1 FROM event_demos e WHERE e.initiative_id = i.id)
                RETURNING id
                """,
                list(demo_columns[0]), [datetime.fromisoformat(t.replace(" ", "T")) for t in demo_columns[1]],
                *[list(col) for col in demo_columns[2:]],
                owner_id,
            )

            outcome_columns = list(zip(*OUTCOMES))
            outcomes = await conn.fetch(
                """
                INSERT INTO outcomes (initiative_id, period_start, metric_id, value, currency, source, recorded_by)
                SELECT i.id, o.period_start, m.id, o.value, o.currency, 'MANUAL', $6
                FROM unnest($1::text[], $2::date[], $3::text[], $4::numeric[], $5::text[])
                     AS o(name, period_start, metric, value, currency)
                JOIN initiatives i ON i.name = o.name
                JOIN outcome_metrics m ON m.code = o.metric
                WHERE NOT EXISTS (SELECT 1 FROM outcomes x WHERE x.initiative_id = i.id)
                RETURNING id
                """,
                *[list(col) for col in outcome_columns],
                owner_id,
            )

            evaluation_columns = list(zip(*EVALUATIONS))
            evaluations = await conn.fetch(
                """
                INSERT INTO initiative_evaluations (initiative_id, target_value, maturity_days, updated_by)
                SELECT i.id, e.target_value, e.maturity_days, $4
                FROM unnest($1::text[], $2::numeric[], $3::int[]) AS e(name, target_value, maturity_days)
                JOIN initiatives i ON i.name = e.name
                ON CONFLICT (initiative_id) DO NOTHING
                RETURNING initiative_id
                """,
                *[list(col) for col in evaluation_columns],
                owner_id,
            )
        print(f"Inserted {len(inserted)} sample initiative(s); {len(SAMPLES) - len(inserted)} already existed.")
        print(f"Added {len(outcomes)} sample result(s) and {len(evaluations)} success setting(s).")
        print(f"Added {len(demos)} sample demo(s).")
        print(f"Added event details for {len(details)} event(s): {', '.join(d['event_code'] for d in details) or 'none'}.")
        print(f"Added {len(costs)} sample cost(s) totalling {sum(c['amount'] for c in costs):,.2f}.")
    finally:
        await close_pool()


if __name__ == "__main__":
    asyncio.run(seed())
