def test_sync_keeps_one_total_per_event_type_and_currency(client, admin, ref, monkeypatch):
    monkeypatch.setenv("NAVAN_CREATE_EVENTS", "false")  # adding events is tested on its own below
    by_name = _event(client, admin, ref)
    navan_name = f"Pytest Navan Offsite {uuid.uuid4().hex[:6]}"
    by_link = _event(client, admin, ref, navan_event_name=navan_name)
    unlinked = f"Pytest Navan Unknown {uuid.uuid4().hex[:6]}"
    bookings = [
        _booking(by_name["name"], 1200.10, start="2090-04-02"),
        _booking(by_name["name"], 300, kind="HOTEL", start="2090-04-01"),
        _booking(by_name["name"], 999, status="VOIDED"),
        _booking(navan_name.upper(), 450),  # names match ignoring case
        _booking(unlinked, 75),
    ]

    summary = _sync(client, admin, monkeypatch, bookings)

    assert (summary["bookings"], summary["created"], summary["updated"], summary["removed"]) == (5, 3, 0, 0)
    assert summary["mode"] == "live"
    seen = {e["name"]: e for e in summary["events"]}
    assert seen[by_name["name"]]["link"] == "NAME_MATCH"
    assert seen[by_name["name"]]["totals"] == [{"currency": "USD", "amount": 1500.1}]
    assert seen[by_name["name"]]["by_type"] == [
        {"booking_type": "FLIGHT", "currency": "USD", "amount": 1200.1, "bookings": 1},
        {"booking_type": "HOTEL", "currency": "USD", "amount": 300.0, "bookings": 1},
    ]
    assert seen[by_name["name"]]["estimate"] is None
    assert seen[navan_name.upper()]["initiative_id"] == by_link["id"]
    assert seen[navan_name.upper()]["link"] == "SET"
    assert seen[unlinked]["initiative_id"] is None
    lines = _navan_lines(by_name["id"])
    assert [(r["external_ref"], r["category"], r["amount"], r["status"], r["description"], r["vendor"], r["incurred_on"])
            for r in lines] == [
        (f"navan:{by_name['id']}:FLIGHT:USD", "FLIGHTS", Decimal("1200.10"), "INVOICED", "Navan flights (1 booking)",
         "Navan", date(2090, 4, 1)),
        (f"navan:{by_name['id']}:HOTEL:USD", "HOTELS", Decimal("300.00"), "INVOICED", "Navan hotels (1 booking)",
         "Navan", date(2090, 4, 1)),
    ]
    assert [r["amount"] for r in _navan_lines(by_link["id"])] == [Decimal("450.00")]

    # Read-only in the cost list, and counted as travel on the event
    costs = client.get(f"/api/initiatives/{by_name['id']}/spend-lines", headers=admin["headers"]).json()
    navan_cost = next(c for c in costs if c["source"] == "NAVAN")
    assert navan_cost["lock_reason"] == "NAVAN"
    overview = client.get("/api/events/overview", params={"search": by_name["event_code"]}, headers=admin["headers"]).json()
    assert (overview[0]["travel_expected"], overview[0]["travel_spent"]) == (1500.1, 1500.1)
    assert overview[0]["navan_actual"] == 1500.1

    # A flight cancelled and another booked, a car, a train and a ferry added; all of an event's bookings
    # cancelled: removed
    bookings[0]["bookingStatus"] = "CANCELED"
    bookings.append(_booking(by_name["name"], 500, start="2090-04-02"))
    bookings.append(_booking(by_name["name"], 80, kind="CAR", start="2090-04-03"))
    bookings.append(_booking(by_name["name"], 40, kind="RAIL", start="2090-04-03"))
    bookings.append(_booking(by_name["name"], 25, kind="FERRY", start="2090-04-03"))
    bookings[3]["bookingStatus"] = "VOIDED"
    summary = _sync(client, admin, monkeypatch, bookings)

    assert (summary["created"], summary["updated"], summary["removed"]) == (3, 1, 1)
    assert [(r["external_ref"].split(":", 2)[2], r["category"], r["amount"], r["description"])
            for r in _navan_lines(by_name["id"])] == [
        ("CAR:USD", "GROUND_TRANSPORT", Decimal("80.00"), "Navan cars (1 booking)"),
        ("FLIGHT:USD", "FLIGHTS", Decimal("500.00"), "Navan flights (1 booking)"),
        ("HOTEL:USD", "HOTELS", Decimal("300.00"), "Navan hotels (1 booking)"),
        ("OTHER:USD", "OTHER_TRAVEL", Decimal("25.00"), "Navan other travel (1 booking)"),
        ("RAIL:USD", "OTHER_TRAVEL", Decimal("40.00"), "Navan rail (1 booking)"),
    ]
    assert _navan_lines(by_link["id"]) == []

    # The Events Overview splits them: flights, hotels, rail and other as travel, cars as ground transport
    start = by_name["start_date"]
    performance = client.get("/api/events/performance", params={"from": start, "to": start},
                             headers=admin["headers"]).json()
    row = next(e for e in performance["events"] if e["id"] == by_name["id"])
    assert row["cost_categories"]["TRAVEL"] == 865
    assert row["cost_categories"]["GROUND_TRANSPORT"] == 80

    # Nothing changed: nothing written
    summary = _sync(client, admin, monkeypatch, bookings)
    assert (summary["created"], summary["updated"], summary["removed"]) == (0, 0, 0)

    status = client.get("/api/integrations/navan/sync-status", headers=admin["headers"]).json()
    assert status["last_error"] is None
    assert status["mode"] == "live"
    assert status["last_run_summary"]["bookings"] == 9


def test_old_lines_are_replaced_by_lines_per_booking_type(client, admin, ref, monkeypatch):
    """Lines from before the split (one per event and currency) are replaced when the event's bookings are read;
    events not read keep theirs, and a reconciled one stays with no per-type lines added on top of it."""
    monkeypatch.setenv("NAVAN_CREATE_EVENTS", "false")
    read = _event(client, admin, ref)
    not_read = _event(client, admin, ref)
    reconciled = _event(client, admin, ref)
    _old_format_line(read["id"], 999)
    _old_format_line(not_read["id"], 777)
    _old_format_line(reconciled["id"], 555, reconciled=True)

    summary = _sync(client, admin, monkeypatch, [
        _booking(read["name"], 600), _booking(read["name"], 250, kind="HOTEL"), _booking(reconciled["name"], 610),
    ])

    assert (summary["created"], summary["removed"], summary["conflicts"]) == (2, 1, 1)
    assert [(r["external_ref"], r["amount"]) for r in _navan_lines(read["id"])] == [
        (f"navan:{read['id']}:FLIGHT:USD", Decimal("600.00")), (f"navan:{read['id']}:HOTEL:USD", Decimal("250.00")),
    ]
    assert [(r["external_ref"], r["amount"]) for r in _navan_lines(not_read["id"])] == [
        (f"navan:{not_read['id']}:USD", Decimal("777.00")),
    ]
    assert [(r["external_ref"], r["amount"]) for r in _navan_lines(reconciled["id"])] == [
        (f"navan:{reconciled['id']}:USD", Decimal("555.00")),
    ]
    [deleted] = run_sql(
        "SELECT old_value FROM audit_logs WHERE entity_type = 'SpendLine' AND action = 'DELETE' "
        "AND actor_user_id IS NULL AND old_value->>'external_ref' = $1",
        f"navan:{read['id']}:USD",
    )
    assert json.loads(deleted["old_value"])["amount"] == "999.00"

    # The next run reads the same: the old line isn't counted as removed again
    summary = _sync(client, admin, monkeypatch, [
        _booking(read["name"], 600), _booking(read["name"], 250, kind="HOTEL"), _booking(reconciled["name"], 610),
    ])
    assert (summary["created"], summary["updated"], summary["removed"]) == (0, 0, 0)


def test_sync_keeps_totals_of_navan_events_it_did_not_read(client, admin, ref, monkeypatch):
    """Bookings are only read for the lookback window: a Navan event missing from a run keeps its event's cost,
    unless the event was linked to another Navan event since the last run."""
    monkeypatch.setenv("NAVAN_CREATE_EVENTS", "false")
    by_name = _event(client, admin, ref)
    still_read = _event(client, admin, ref, navan_event_name=f"Pytest Navan Read {uuid.uuid4().hex[:6]}")
    moved = _event(client, admin, ref, navan_event_name=f"Pytest Navan Before {uuid.uuid4().hex[:6]}")
    bookings = [
        _booking(by_name["name"], 500),
        _booking(still_read["navan_event_name"], 200),
        _booking(moved["navan_event_name"], 300),
    ]
    summary = _sync(client, admin, monkeypatch, bookings)
    assert summary["created"] == 3

    # The event is now linked to another Navan event, with no bookings read yet
    response = client.patch(
        f"/api/initiatives/{moved['id']}",
        json={"event": {"navan_event_name": f"Pytest Navan After {uuid.uuid4().hex[:6]}"}},
        headers=admin["headers"],
    )
    assert response.status_code == 200, response.text

    # Only one Navan event's bookings are still in the window
    summary = _sync(client, admin, monkeypatch, [_booking(still_read["navan_event_name"], 250)])

    assert (summary["created"], summary["updated"], summary["removed"]) == (0, 1, 1)
    assert [r["amount"] for r in _navan_lines(by_name["id"])] == [Decimal("500.00")]  # not read: kept
    assert [r["amount"] for r in _navan_lines(still_read["id"])] == [Decimal("250.00")]
    assert _navan_lines(moved["id"]) == []  # linked elsewhere: removed

    # Still kept on the next run; once its bookings are read again and all cancelled, removed
    summary = _sync(client, admin, monkeypatch, [_booking(still_read["navan_event_name"], 250)])
    assert (summary["created"], summary["updated"], summary["removed"]) == (0, 0, 0)
    summary = _sync(client, admin, monkeypatch, [_booking(by_name["name"], 500, status="CANCELED")])
    assert _navan_lines(by_name["id"]) == []
    assert [r["amount"] for r in _navan_lines(still_read["id"])] == [Decimal("250.00")]


def test_sync_adds_missing_events(client, admin, ref, monkeypatch):
    """A Navan event with active bookings and no event here gets one, linked to it and with its travel cost."""
    name = f"Pytest Navan Show {uuid.uuid4().hex[:6]}"
    cancelled_only = f"Pytest Navan Called Off {uuid.uuid4().hex[:6]}"
    monkeypatch.setenv("NAVAN_CREATE_EVENTS", "true")  # off by default
    bookings = [
        {**_booking(name, 640.25, kind="HOTEL", start="2090-05-04"), "endDate": "2090-05-06",
         "destination": {"city": "Tampa", "country": "United States"}},
        _booking(name, 210, start="2090-05-04"),
        _booking(cancelled_only, 300, status="CANCELED"),  # nothing active: no event
    ]

    summary = _sync(client, admin, monkeypatch, bookings)

    assert (summary["events_created"], summary["created"]) == (1, 2)  # a hotel line and a flight line
    seen = {e["name"]: e for e in summary["events"]}
    assert seen[name]["link"] == "SET"
    assert seen[cancelled_only]["initiative_id"] is None
    created = client.get(f"/api/initiatives/{seen[name]['initiative_id']}", headers=admin["headers"]).json()
    assert (created["name"], created["brand_name"], created["channel_name"], created["status"]) == (
        name, "TBD/All", "Events", "PLANNED",  # Upcoming: it hasn't started
    )
    assert (created["start_date"], created["end_date"], created["city"], created["country_code"]) == (
        "2090-05-04", "2090-05-06", "Tampa", "US",
    )
    assert created["navan_event_name"] == name
    assert [r["amount"] for r in _navan_lines(created["id"])] == [Decimal("210.00"), Decimal("640.25")]

    # The next run finds it linked and adds nothing
    summary = _sync(client, admin, monkeypatch, bookings)
    assert (summary["events_created"], summary["created"], summary["updated"]) == (0, 0, 0)

    # Switched off: Navan events stay unlinked
    monkeypatch.setenv("NAVAN_CREATE_EVENTS", "false")
    other = f"Pytest Navan Other Show {uuid.uuid4().hex[:6]}"
    summary = _sync(client, admin, monkeypatch, [*bookings, _booking(other, 99)])
    assert summary["events_created"] == 0
    assert {e["name"]: e for e in summary["events"]}[other]["initiative_id"] is None


def test_sync_keeps_linked_events_up_to_date_without_duplicates(client, admin, ref, monkeypatch):
    """Each sync updates linked events' status by their dates (Upcoming, In progress, Completed), fills a
    missing city, never changes dates or a status set on purpose, never creates a second event, and leaves ignored
    Navan names alone."""
    monkeypatch.setenv("NAVAN_CREATE_EVENTS", "true")
    past = _event(client, admin, ref, start=date.today() - timedelta(days=10))
    # An event from before cities were required
    run_sql("UPDATE event_details SET city = NULL, country_code = NULL WHERE initiative_id = $1", uuid.UUID(past["id"]))
    upcoming = _event(client, admin, ref, start=date.today() + timedelta(days=5))
    cancelled = _event(client, admin, ref, start=date.today() - timedelta(days=10))
    assert client.patch(f"/api/initiatives/{cancelled['id']}", json={"status": "CANCELLED"},
                        headers=admin["headers"]).status_code == 200
    stray = f"Pytest Navan Stray {uuid.uuid4().hex[:6]}"
    monkeypatch.setenv("NAVAN_IGNORE_EVENTS", f"Something Else, {stray.upper()}")
    bookings = [
        {**_booking(past["name"], 300, kind="HOTEL"), "destination": {"city": "Mesa", "country": "United States"}},
        _booking(upcoming["name"], 200),
        _booking(cancelled["name"], 100),
        _booking(stray, 50),
    ]

    summary = _sync(client, admin, monkeypatch, bookings)

    get = lambda e: client.get(f"/api/initiatives/{e['id']}", headers=admin["headers"]).json()  # noqa: E731
    assert (get(past)["status"], get(past)["city"], get(past)["country_code"]) == ("COMPLETED", "Mesa", "US")
    assert get(upcoming)["status"] == "PLANNED"
    assert get(cancelled)["status"] == "CANCELLED"
    assert (get(past)["start_date"], get(past)["end_date"]) == (past["start_date"], past["end_date"])
    assert summary["events_updated"] == 1  # the past one; the upcoming one was already Upcoming
    assert summary["events_created"] == 0
    assert stray not in {e["name"] for e in summary["events"]}
    assert run_sql("SELECT count(*) AS n FROM initiatives WHERE name = $1", stray)[0]["n"] == 0

    # Again: nothing new, nothing duplicated
    summary = _sync(client, admin, monkeypatch, bookings)
    assert (summary["events_created"], summary["events_updated"], summary["created"]) == (0, 0, 0)
    for e in (past, upcoming, cancelled):
        assert run_sql("SELECT count(*) AS n FROM initiatives WHERE name = $1", e["name"])[0]["n"] == 1


