def _booking(event_name, total, *, status="TICKETED", currency="USD", start="2090-03-10", kind="FLIGHT"):
    return {"bookingId": uuid.uuid4().hex, "eventName": event_name, "grandTotal": total, "currency": currency,
            "bookingStatus": status, "startDate": f"{start}T09:00:00", "bookingType": kind}


def _event(client, admin, ref, name=None, navan_event_name=None, expect=201, *, start=None, status="PLANNED",
           currency="USD", budget=20000, **event_fields):
    start = start or date.today() + timedelta(days=30)
    event = {"city": "Phoenix", "country_code": "US", **event_fields}
    if navan_event_name is not None:
        event["navan_event_name"] = navan_event_name
    response = client.post("/api/initiatives", json={
        "name": name or f"Pytest Navan Event {uuid.uuid4().hex[:6]}",
        "brand_id": ref["brands"]["DESKFLEX"],
        "channel_id": ref["channels"]["EVENTS"],
        "sub_channel_id": ref["sub_channels"]["IN_PERSON_EVENTS"],
        "start_date": start.isoformat(),
        "end_date": (start + timedelta(days=2)).isoformat(),
        "budget_amount": budget,
        "currency": currency,
        "status": status,
        "event": event,
    }, headers=admin["headers"])
    assert response.status_code == expect, response.text
    return response.json()


def _sync(client, admin, monkeypatch, bookings):
    async def fake_fetch():
        return bookings

    monkeypatch.setattr(navan_cost_sync_job, "fetch_navan_bookings", fake_fetch)
    response = client.post("/api/integrations/navan/sync-costs", headers=admin["headers"])
    assert response.status_code == 200, response.text
    return response.json()


def _navan_lines(initiative_id):
    return run_sql(
        "SELECT s.amount, s.currency, s.status, s.description, s.vendor, s.incurred_on, s.external_ref, "
        "c.code AS category FROM spend_lines s JOIN spend_categories c ON c.id = s.category_id "
        "WHERE s.source = 'NAVAN' AND s.initiative_id = $1 ORDER BY s.external_ref",
        uuid.UUID(initiative_id),
    )


def _old_format_line(initiative_id, amount, *, reconciled=False):
    """A Navan line as the sync kept them before the split by booking type: one per event and currency."""
    run_sql(
        "INSERT INTO spend_lines (initiative_id, category_id, description, vendor, status, amount, currency, "
        "incurred_on, cost_type, source, external_ref, reconciled_month) "
        "SELECT $1, id, 'Navan travel (2 bookings)', 'Navan', 'INVOICED', $2, 'USD', DATE '2090-03-10', 'OPEX', "
        "'NAVAN', $3, $4 FROM spend_categories WHERE code = 'OTHER_TRAVEL'",
        uuid.UUID(initiative_id), amount, f"navan:{initiative_id}:USD", date(2090, 3, 1) if reconciled else None,
    )


