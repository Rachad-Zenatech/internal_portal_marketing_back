def test_navan_estimate_on_create_and_update(client, admin, ref):
    # Not limited by the event budget, unlike the travel budget
    created = _event(client, admin, ref, budget=2000, navan_estimate_amount=4500.5)

    assert created["navan_estimate_amount"] == 4500.5
    shown = client.get(f"/api/initiatives/{created['id']}", headers=admin["headers"]).json()
    assert shown["navan_estimate_amount"] == 4500.5
    listed = client.get("/api/initiatives", params={"search": created["event_code"]}, headers=admin["headers"]).json()
    assert listed["items"][0]["navan_estimate_amount"] == 4500.5
    [audit] = run_sql(
        "SELECT new_value FROM audit_logs WHERE entity_type = 'Initiative' AND entity_id = $1 AND action = 'CREATE'",
        created["id"],
    )
    assert json.loads(audit["new_value"])["event"]["navan_estimate_amount"] == 4500.5

    response = client.patch(f"/api/initiatives/{created['id']}", json={"event": {"navan_estimate_amount": 5200}},
                            headers=admin["headers"])
    assert response.status_code == 200, response.text
    assert response.json()["navan_estimate_amount"] == 5200
    [audit] = run_sql(
        "SELECT old_value, new_value FROM audit_logs WHERE entity_type = 'Initiative' AND entity_id = $1 "
        "AND action = 'UPDATE'",
        created["id"],
    )
    assert json.loads(audit["old_value"])["event"] == {"navan_estimate_amount": 4500.5}
    assert json.loads(audit["new_value"])["event"]["navan_estimate_amount"] == 5200

    cleared = client.patch(f"/api/initiatives/{created['id']}", json={"event": {"navan_estimate_amount": None}},
                           headers=admin["headers"])
    assert cleared.json()["navan_estimate_amount"] is None


