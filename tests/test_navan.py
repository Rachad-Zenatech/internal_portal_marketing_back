    assert daas["last_travel"] == date(2090, 10, 22)  # the hotel's check-out
    assert (daas["city"], daas["country_code"]) == ("Mesa", "US")  # where the hotel is, over where flights land
    assert events["all cancelled"]["totals"] == {}


