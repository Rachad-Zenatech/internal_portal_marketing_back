def test_demo_bookings_are_the_same_on_every_run():
    event = _demo_event()
    booked_by_then = date(2090, 7, 1)

    first, estimate = generate_event_bookings(event, booked_by_then)
    again, same_estimate = generate_event_bookings(_demo_event(), booked_by_then)

    assert (first, estimate) == (again, same_estimate)
    active = [b for b in first if b["bookingStatus"] not in INACTIVE_STATUSES]
    assert {b["bookingType"] for b in active} <= {"FLIGHT", "HOTEL", "CAR"}
    assert {b["eventName"] for b in first} == {event["name"]}
    assert {b["currency"] for b in first} == {"USD"}
    # A finished event is fully booked: the estimate is what was booked
    assert estimate == sum(Decimal(b["grandTotal"]) for b in active)
    travellers = {b["bookingId"].split("-")[2] for b in first}
    assert 3 <= len(travellers) <= 12
    # Other dates: other bookings
    moved, _ = generate_event_bookings(_demo_event(start=date(2090, 6, 11)), booked_by_then)
    assert moved != first


def test_demo_estimate_forecasts_travellers_not_booked_yet():
    event = _demo_event()

    nothing_yet, estimate_before = generate_event_bookings(event, date(2090, 1, 1))
    booked, estimate_after = generate_event_bookings(event, date(2090, 7, 1))

    assert nothing_yet == []
    assert estimate_before > 0
    # The forecast is what those travellers book later (cancelled trips aside)
    assert estimate_before >= estimate_after
    # Part way: booked so far, plus the forecast for the rest
    some, estimate_mid = generate_event_bookings(event, date(2090, 5, 15))
    active = sum(Decimal(b["grandTotal"]) for b in some if b["bookingStatus"] not in INACTIVE_STATUSES)
    assert estimate_mid >= active
    assert len(some) <= len(booked)


def test_demo_mode_only_touches_demo_events(client, admin, ref, monkeypatch):
    monkeypatch.setenv("NAVAN_CREATE_EVENTS", "true")  # never in demo mode
    real = _event(client, admin, ref)
    _sync(client, admin, monkeypatch, [_booking(real["name"], 640)])
    real_lines = _navan_lines(real["id"])
    assert len(real_lines) == 1
    past = date.today() - timedelta(days=40)
    demo = _event(client, admin, ref, name=f"{DEMO_EVENT_PREFIX}Pytest Navan Expo {uuid.uuid4().hex[:6]}",
                  start=past, status="COMPLETED")
    draft = _event(client, admin, ref, name=f"{DEMO_EVENT_PREFIX}Pytest Navan Draft {uuid.uuid4().hex[:6]}",
                   status="DRAFT")
    cancelled = _event(client, admin, ref, name=f"{DEMO_EVENT_PREFIX}Pytest Navan Off {uuid.uuid4().hex[:6]}",
                       start=past, status="CANCELLED")

    async def navan_must_not_be_called():
        raise AssertionError("Navan was called in demo mode")

    monkeypatch.setattr(navan_cost_sync_job, "fetch_navan_bookings", navan_must_not_be_called)
    monkeypatch.setenv("NAVAN_MODE", "demo")
    response = client.post("/api/integrations/navan/sync-costs", headers=admin["headers"])
    assert response.status_code == 200, response.text
    summary = response.json()

    assert summary["mode"] == "demo"
    assert summary["events_created"] == 0
    seen = {e["name"]: e for e in summary["events"]}
    assert real["name"] not in seen
    assert draft["name"] not in seen and cancelled["name"] not in seen
    assert all(name.startswith(DEMO_EVENT_PREFIX) for name in seen)
    assert seen[demo["name"]]["initiative_id"] == demo["id"]
    # The real event's line is left as it was
    assert _navan_lines(real["id"]) == real_lines
    lines = _navan_lines(demo["id"])
    assert {r["category"] for r in lines} <= {"FLIGHTS", "HOTELS", "GROUND_TRANSPORT"}
    assert {"FLIGHTS", "HOTELS"} <= {r["category"] for r in lines}
    actual = sum(r["amount"] for r in lines)
    assert float(actual) == seen[demo["name"]]["totals"][0]["amount"]
    assert _navan_lines(draft["id"]) == [] and _navan_lines(cancelled["id"]) == []

    # Its estimate is set from the generated one (fully booked: the actual), audited as the sync's change
    shown = client.get(f"/api/initiatives/{demo['id']}", headers=admin["headers"]).json()
    assert shown["navan_estimate_amount"] == float(actual) == seen[demo["name"]]["estimate"]["amount"]
    [audit] = run_sql(
        "SELECT old_value, new_value FROM audit_logs WHERE entity_type = 'Initiative' AND entity_id = $1 "
        "AND action = 'UPDATE' AND actor_user_id IS NULL",
        demo["id"],
    )
    assert json.loads(audit["old_value"]) == {"event": {"navan_estimate_amount": None}}
    assert json.loads(audit["new_value"])["event"]["navan_estimate_amount"] == str(actual)
    [card] = client.get("/api/events/overview", params={"search": demo["event_code"]}, headers=admin["headers"]).json()
    assert (card["navan_estimate_amount"], card["navan_actual"]) == (float(actual), float(actual))

    status = client.get("/api/integrations/navan/sync-status", headers=admin["headers"]).json()
    assert (status["mode"], status["configured"]) == ("demo", True)
    assert status["last_run_summary"]["mode"] == "demo"

    # The same data on the next run: nothing written
    response = client.post("/api/integrations/navan/sync-costs", headers=admin["headers"])
    assert response.status_code == 200, response.text
    again = response.json()
    assert (again["created"], again["updated"], again["removed"], again["estimates_updated"]) == (0, 0, 0, 0)
    assert _navan_lines(demo["id"]) == lines

    # Back to live: the live state is its own
    monkeypatch.setenv("NAVAN_MODE", "live")
    status = client.get("/api/integrations/navan/sync-status", headers=admin["headers"]).json()
    assert status["mode"] == "live"
    assert status["last_run_summary"]["mode"] == "live"


